local out=assert(os.getenv('NES_LINK_OUTPUT'))
local f=assert(io.open(out..'/validation.txt','w'))
local input={};local total=0
emu.speedmode('normal')
emu.registerbefore(function() joypad.set(1,input) end)
local function step(n,pad) input=pad or {};for i=1,n do emu.frameadvance() end end
local function tap(key) step(2,{[key]=true});step(14) end
local function check(ok,label) assert(ok,label);total=total+1;f:write('PASS '..label..'\n');f:flush() end
local function v(a) return memory.readbyte(a) end
local function capture(name)
 emu.speedmode('normal');step(240)
 local img=assert(io.open(out..'/'..name..'.gd','wb'));img:write(gui.gdscreenshot());img:close()
 emu.speedmode('maximum')
end
local function open() tap('A');check(v(13)==1,'Open wardrobe menu') end
local function choose(n) for i=1,n do tap('down') end;tap('A') end
step(240)
check(v(0)==40 and v(1)==128 and v(14)==0,'Initial position and puzzle state')
capture('room')
local base=0;local worst=0
memory.registerexec(memory.readword(0xfffa),function() base=debugger.getcyclescount() end)
memory.registerwrite(0x2007,function() local d=debugger.getcyclescount()-base;if d>worst then worst=d end end)
tap('A');check(v(13)==2 and v(16)==4,'Far interaction feedback');tap('B')
check(v(13)==0,'B closes dialogue')
step(90,{right=true});step(2)
check(v(0)==96,'Desk blocks movement')
tap('A');check(v(16)==5 and v(14)==0,'Examine desk without changing puzzle');tap('B')
step(50,{down=true});step(300,{right=true});step(2)
check(v(0)==216 and v(1)==168,'Bottom and right room bounds')
step(300,{up=true});step(2)
check(v(1)==104,'Wardrobe collision')
step(2,{start=true});local x=v(0);step(30,{left=true,start=true});step(2)
check(v(5)==1 and v(0)==x,'Pause and Start hold do not move or retrigger')
tap('A');check(v(13)==0,'No interaction while paused');tap('start')
tap('select');check(v(0)==40 and v(1)==128,'Select repositions')
step(48,{up=true});step(160,{right=true});step(2)
check(v(0)==168 and v(1)==80,'Top bound and wardrobe side collision')
step(24,{down=true});step(32,{right=true});step(2)
check(v(0)==200 and v(1)==104,'Reach wardrobe via open path')
open();step(30,{right=true});step(2)
check(v(0)==200 and v(1)==104,'Menu freezes movement')
choose(2);check(v(14)==0 and v(16)==9,'Door locked before clue and latch');tap('B')
open();choose(1);check(v(14)==0 and v(16)==7,'Drawer blocked before mirror clue');tap('B')
open();tap('B');check(v(13)==0 and v(14)==0,'Cancel menu does not advance puzzle')
open();step(60,{A=true});step(14)
check(v(14)==1 and v(13)==2 and v(16)==6,'Mirror clue and no repeated held-A activation')
capture('clue');tap('B')
open();choose(2);check(v(14)==1 and v(16)==9,'Clue alone does not open door');tap('B')
open();choose(1);check(v(14)==2 and v(16)==8,'Drawer releases hidden latch');tap('B')
open();choose(1);check(v(14)==2 and v(16)==13,'Repeated drawer inspection is idempotent');tap('B')
open();choose(2);check(v(14)==3 and v(16)==10,'Door opens after latch')
check(ppu.readbyte(0x20f7)==176,'Open wardrobe graphics uploaded')
capture('open');tap('B')
tap('A');check(v(14)==4 and v(16)==11,'Objects collected only on a separate interaction')
check(ppu.readbyte(0x20f7)==212,'Empty wardrobe graphics uploaded')
local title=ppu.readbyterange(0x2065,21)
check(string.find(title,'LIVRO: SIM',1,true)~=nil and string.find(title,'ADAGA: SIM',1,true)~=nil,'Inventory HUD shows both objects')
capture('collected');tap('B')
tap('A');check(v(14)==4 and v(13)==4 and v(16)==15,'Passage offered without recollecting objects');tap('B')
tap('start');tap('select');check(v(14)==4 and v(13)==0 and v(0)==40 and v(5)==1,'Select preserves collected objects during pause');tap('start')
-- Do not measure the full-screen loading transfer as VBlank-only work.
memory.registerexec(memory.readword(0xfffa),nil);memory.registerwrite(0x2007,nil)
check(worst>0 and worst<2200,'Bedroom PPU jobs fit VBlank: '..worst..' cycles')
-- Restore access to the wardrobe after the Select regression.
step(48,{up=true});step(160,{right=true});step(24,{down=true});step(32,{right=true});step(14)
tap('B');check(v(13)==3 and v(16)==17,'B opens inventory')
tap('A');check(v(23)==0 and v(16)==20,'Book in bedroom does not reveal a distant room');tap('B')
tap('A');check(v(13)==4 and v(21)==0,'Passage requires confirmation')
tap('B');check(v(21)==0 and v(13)==0,'Cancel passage stays in bedroom')
tap('A');tap('A');step(30)
check(v(21)==1 and v(0)==40 and v(1)==128 and v(14)==4,'Enter room 2 with items')
check(ppu.readbyte(0x21ba)==131,'Gate initially closed')
check(ppu.readbyte(0x2214)==129,'Tether initially hidden')
capture('antechamber')
local loader=assert(tonumber(os.getenv('NES_LOADER_PC')))
local loading=false;local transfer_writes=0;local room_worst=0
memory.registerexec(memory.readword(0xfffa),function() base=debugger.getcyclescount();loading=false end)
memory.registerexec(loader,function() loading=true end)
memory.registerwrite(0x2007,function()
 if loading then transfer_writes=transfer_writes+1
 else local d=debugger.getcyclescount()-base;if d>room_worst then room_worst=d end end
end)
-- Use the dagger before revealing: must not solve the seal.
tap('B');tap('down');tap('A')
check(v(23)==0 and v(16)==23,'Dagger cannot cut hidden link');tap('B')
step(300,{right=true});step(14)
check(v(0)==192,'Closed gate blocks movement')
tap('A');check(v(16)==26 and v(25)==0,'Cannot finish before cutting');tap('B')
tap('select');check(v(21)==1 and v(0)==40 and v(14)==4,'Select stays in current room with inventory')
tap('B');tap('A');check(v(23)==1 and v(16)==21,'Book reveals the link')
check(ppu.readbyte(0x2214)==136,'Revealed tether rendered')
check(ppu.readbyte(0x221a)==131,'Tether update does not overwrite gate')
capture('revealed');tap('B')
tap('B');tap('A');check(v(23)==1 and v(16)==22,'Repeated reveal preserves link');tap('B')
tap('B');tap('down');tap('A');check(v(23)==1 and v(16)==24,'Dagger out of range cannot cut');tap('B')
-- Return before solving; verify persistent state and bedroom reconstruction.
tap('A');step(30)
check(v(21)==0 and v(14)==4 and v(23)==1,'Return to bedroom preserves inventory and revealed link')
check(ppu.readbyte(0x20f7)==212,'Bedroom restores empty wardrobe')
step(8,{up=true});step(2);tap('A');tap('A');step(30)
check(v(21)==1 and v(23)==1 and ppu.readbyte(0x2214)==136,'Reenter restores revealed link')
step(140,{right=true});step(14)
check(v(0)==180,'Approach link without crossing gate')
-- Pausing prevents item use.
tap('start');tap('B');check(v(13)==0 and v(23)==1,'Pause prevents item use');tap('start')
tap('B');tap('down');tap('A')
check(v(23)==2 and v(16)==25,'Dagger cuts revealed link within reach')
check(ppu.readbyte(0x2214)==129,'Cut tether disappears')
check(ppu.readbyte(0x21ba)==132,'Gate switches to open graphics')
capture('cut');tap('B')
tap('B');tap('down');tap('A');check(v(23)==2 and v(16)==29,'Repeated cutting is idempotent');tap('B')
step(60,{right=true});step(14)
check(v(0)==216,'Open gate no longer blocks movement')
tap('A');check(v(25)==1 and v(16)==27,'Open passage reaches test ending');tap('B')
tap('B');tap('A');check(v(23)==2 and v(16)==29,'Book cannot recreate a cut link');tap('B')
step(190,{left=true});step(14);tap('A');step(30)
check(v(21)==0 and v(23)==2 and v(25)==1,'Return preserves completed state')
step(8,{up=true});step(2);tap('A');tap('A');step(30)
check(v(21)==1 and v(23)==2 and ppu.readbyte(0x21ba)==132,'Reenter restores open gate')
check(transfer_writes==4*1024,'Four measured scene loads upload exactly 1024 bytes each')
check(room_worst>0 and room_worst<2200,'Room 2 PPU jobs fit VBlank: '..room_worst..' cycles')
memory.registerexec(memory.readword(0xfffa),nil);memory.registerexec(loader,nil);memory.registerwrite(0x2007,nil)
emu.softreset();step(240)
check(v(14)==0 and v(13)==0 and v(0)==40 and v(5)==0 and v(21)==0 and v(23)==0 and v(25)==0,'Reset starts a new puzzle and clears room/link/completion')
check(ppu.readbyte(0x20f7)==140,'Reset restores closed wardrobe')
check(string.find(ppu.readbyterange(0x2065,21),'LIVRO: NAO',1,true)~=nil,'Reset clears inventory')
f:write('TOTAL '..total..' checks passed\n');f:close();emu.exit()
